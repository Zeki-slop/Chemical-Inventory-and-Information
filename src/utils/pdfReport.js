import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

/**
 * Generates a simple, print-friendly PDF summary of a product/chemical's
 * safety information, so users can save or share it offline.
 */
export function downloadProductReportPdf(item, safety) {
  const doc = new jsPDF();

  doc.setFontSize(18);
  doc.text('ChemAware Safety Report', 14, 18);

  doc.setFontSize(12);
  doc.text(item.name || 'Unknown product', 14, 28);

  doc.setFontSize(10);
  doc.setTextColor(100);
  doc.text(`Generated: ${new Date().toLocaleString()}`, 14, 34);

  const rows = [
    ['Safety Score', `${safety.score}/100 (${safety.level})`],
    ['CAS Number', item.casNumber || '—'],
    ['Molecular Formula', item.molecularFormula || '—'],
    ['Molecular Weight', item.molecularWeight ? `${item.molecularWeight} g/mol` : '—'],
    ['Manufacturer', item.manufacturer || '—'],
    ['Category', item.category || '—'],
  ];

  autoTable(doc, {
    startY: 40,
    head: [['Field', 'Value']],
    body: rows,
    theme: 'grid',
    headStyles: { fillColor: [13, 110, 253] },
  });

  let y = doc.lastAutoTable.finalY + 10;

  const sections = [
    ['Common Uses', item.uses || item.indications],
    ['Health Risks', item.hazards || item.warnings],
    ['Side Effects', item.sideEffects],
    ['Toxicity', item.toxicity],
  ];

  sections.forEach(([title, list]) => {
    if (!list || list.length === 0) return;
    if (y > 260) { doc.addPage(); y = 20; }
    doc.setFontSize(12);
    doc.setTextColor(20);
    doc.text(title, 14, y);
    y += 6;
    doc.setFontSize(9);
    doc.setTextColor(80);
    list.slice(0, 4).forEach((line) => {
      const wrapped = doc.splitTextToSize(`• ${line}`, 180);
      doc.text(wrapped, 14, y);
      y += wrapped.length * 5 + 2;
    });
    y += 4;
  });

  doc.setFontSize(8);
  doc.setTextColor(150);
  doc.text('Generated by ChemAware — data sourced from PubChem, OpenFDA, and Open Food Facts.', 14, 290);

  doc.save(`${(item.name || 'chemaware-report').replace(/\s+/g, '_')}.pdf`);
}
